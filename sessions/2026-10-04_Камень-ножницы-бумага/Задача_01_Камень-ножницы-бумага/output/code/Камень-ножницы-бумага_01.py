# Игра «Камень, ножницы, бумага»: определение победителя
# Словесный алгоритм из spec.md, переведенный в код

a = input("Игрок 1, введи камень, ножницы или бумага: ").lower()
b = input("Игрок 2, введи камень, ножницы или бумага: ").lower()

if a == b:
    print("Ничья")
elif a == "бумага" and b == "камень":
    print("Победил игрок 1")
elif a == "камень" and b == "ножницы":
    print("Победил игрок 1")
elif a == "ножницы" and b == "бумага":
    print("Победил игрок 1")
else:
    print("Победил игрок 2")
