"""Перестановка второй и третьей цифр трехзначного числа.

Вариант 4: стиль учителя, цифры и умножение на разряд.
Задача: дано трехзначное число, получить число, образованное перестановкой
второй и третьей цифр. Пример: 456 -> 465.

Стиль учителя: ввод в переменную, цифры умножаются на разряд. Деление и
остаток не используются.
"""

